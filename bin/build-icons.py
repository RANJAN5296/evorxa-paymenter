#!/usr/bin/env python3
"""Build extension/Evorxa/resources/assets/icons.css: Remix Icon glyphs for the fa-* classes the panel uses.

Usage: bin/build-icons.py /path/to/paymenter   (reads vendor/andreiio/blade-remix-icon/resources/svg)
Remix Icon is licensed under Apache-2.0 (https://remixicon.com).
"""
import base64, os, sys

MAP = {
    'archive': 'archive-line', 'chart-area': 'line-chart-line', 'compact-disc': 'disc-line', 'copy': 'file-copy-line',
    'cube': 'box-3-line', 'exclamation-circle': 'error-warning-line', 'exclamation-triangle': 'alert-line',
    'eye': 'eye-line', 'eye-slash': 'eye-off-line', 'fire-alt': 'fire-line', 'grip-vertical': 'draggable',
    'hourglass-half': 'hourglass-line', 'key': 'key-2-line', 'lock': 'lock-line', 'map-marker-alt': 'map-pin-line',
    'network-wired': 'router-line', 'pen': 'pencil-line', 'play': 'play-fill', 'power-off': 'shut-down-line',
    'redo': 'restart-line', 'server': 'server-line', 'shield-alt': 'shield-check-line', 'stop': 'stop-fill',
    'sync-alt': 'refresh-line', 'terminal': 'terminal-box-line', 'tools': 'tools-line', 'trash-alt': 'delete-bin-line',
    'microchip': 'cpu-line', 'memory': 'ram-2-line', 'hdd': 'hard-drive-3-line', 'credit-card': 'bank-card-line',
    'check': 'check-line', 'times': 'close-line', 'plus': 'add-line', 'info-circle': 'information-line',
}

src = os.path.join(sys.argv[1] if len(sys.argv) > 1 else '.', 'vendor/andreiio/blade-remix-icon/resources/svg')
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'extension/Evorxa/resources/assets/icons.css')
scope = ':where([class*="evx"]) i:is(.fas, .far, .fab)'
lines = [
    '/* Generated by bin/build-icons.py - Remix Icon (Apache-2.0, remixicon.com) glyphs for the fa-* classes of the Evorxa panel. */',
    scope + ' { display: inline-block; width: 1em; height: 1em; vertical-align: -0.14em; font-style: normal; flex: none;'
    ' background-color: currentColor; -webkit-mask: var(--evx-i) center / contain no-repeat; mask: var(--evx-i) center / contain no-repeat; }',
    scope + '::before { content: none; }',
]
for fa, ri in sorted(MAP.items()):
    path = os.path.join(src, ri + '.svg')
    if not os.path.isfile(path):
        sys.exit('missing icon: ' + ri)
    data = base64.b64encode(open(path, 'rb').read()).decode()
    lines.append(':where([class*="evx"]) i.fa-%s { --evx-i: url("data:image/svg+xml;base64,%s"); }' % (fa, data))
open(out, 'w').write('\n'.join(lines) + '\n')
print('wrote', os.path.normpath(out), len(MAP), 'icons')
